#!/usr/bin/env python3
"""The context-setting census for the Phase 5 DB lane, GENERATED.

ROUND 18, THE COORDINATOR'S B-5. Round 17 wrote "per SESSION at 23 of this
lane's 25 call sites" and "Two sites set the context per transaction". Both
were true when written and both were false in the SAME COMMIT that wrote
them, because that commit added one more `'transaction'` site (the M60 case)
and nobody re-counted. It is the fourth time a figure in this phase went out
wrong by being reasoned about instead of read off a run, and the coordinator's
instruction was: generate the figures, so the next added case cannot falsify
them again.

So the census is computed here, from the same corpus and the same two
patterns the pure law uses
(`test/db-refusals-name-their-defence.test.ts`, "pins how many call sites set
the request context"), and rendered into the documents that used to state it
by hand. The law still PINS the session count — it fails when the number
moves — and this tool makes the DOCUMENTS follow the corpus instead of
following a memory of it.

`--check` exits 1 on three distinct failures, the same three as
`tools/status-block.py`:

  * a rendered block that DIFFERS from the corpus (drift),
  * a listed document that carries NO sentinel pair (absence),
  * a sentinel pair that is malformed or unclosed.

Run it BEFORE `tools/status-block.py` and `tools/manifest-digests.py`: the
digests hash the bytes these two tools leave behind.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

BEGIN = "<!-- P5-CONTEXT-SITES:BEGIN — generated by tools/context-sites.py; do not edit by hand -->"
END = "<!-- P5-CONTEXT-SITES:END -->"

# The documents that state the census. A document listed here and carrying no
# block FAILS: a check that only compares what it finds passes when a document
# quietly stops being checked.
DOCUMENTS = ["P5-CHECKPOINT.md", "P5-CHALLENGE-RESPONSE-2597219.md"]

HELPER = re.compile(r"setRequestContext\([^;]*?'(session|transaction)'\s*\)")
LITERAL = re.compile(r"set_config\('app\.[a-z_]+'[^)]*,\s*false\s*\)")
COMMENT = re.compile(r"//.*$")

# ROUND 23, THE CHALLENGER'S B-4. The two patterns above do not count
# context-setting sites; they count what two spellings match. A THIRD spelling
# sets the context and was invisible to both — and it is not contrived, it is
# the line `cluster.ts` itself uses, with the scope argument BOUND rather than
# the literal `false`:
#
#   c.query(`SELECT set_config('app.tenant_id', $1, $3), …`, [t, b, false]);
#
# Planted in the corpus, the pure law stayed green and the census did not move,
# while a session-scoped site had been added. The figures were right and the
# sentence about what KEEPS them right was wrong — the third sentence in this
# phase to over-claim its own instrument.
#
# This detector is the fail-closed half of the remedy, in the shape
# `manifest-digests.py`'s LOOKS_LIKE_REVIEWER already has: a BROAD pattern for
# every way of writing a context set that this lane could plausibly use, each
# match of which must be ACCOUNTED FOR by one of the two counted forms. A match
# that is not is a PROBLEM, never a quiet zero. It cannot be exhaustive — no
# regex over a corpus can be — so the footnote the tool renders claims exactly
# this and not more.
# ROUND 24, THE CHALLENGER'S B-6: the sentence named `SET app.…` while the
# pattern required `app.` IMMEDIATELY after SET, so `SET LOCAL app.tenant_id`
# — the PostgreSQL spelling for the transaction-scoped setting this census
# exists to distinguish — passed both the law and the census untouched. That
# is a hole INSIDE the shape the sentence names, which is not what "not a
# claim of exhaustiveness" covers.
#
# ROUND 24 ALSO WIDENS THE NET to the other shapes the challenger measured as
# misses (its F-43), because the coordinator asked for cover rather than a
# clause where cover is cheap: a BOUND key `set_config($1, $2, false)`, an
# INTERPOLATED key `set_config('app.${k}', …)`, and `set_config (` with a
# space. Ordinary non-`app.` settings — `set_config('statement_timeout', …)` —
# are deliberately NOT matched, so the net does not cry wolf about settings
# that are nothing to do with the request context.
#
# STILL UNCOVERED, named in the rendered footnote rather than papered over:
# anything in `test/db/helpers/*.ts` or any non-`.test.ts` file under
# `test/db`, which is the census's declared corpus — `cluster.ts`'s own
# internal line lives there, and counting a helper's IMPLEMENTATION as a call
# site would be wrong, so the scope limit is stated instead.
BROAD = re.compile(
    r"set_config\s*\(\s*'app\.[a-z_]+'"
    r"|set_config\s*\(\s*\$\d+"
    r"|set_config\s*\(\s*[`'\"][^`'\"]*\$\{"
    r"|(?<![\w.])SET\s+(?:LOCAL\s+|SESSION\s+)?\"?app\.[a-z_]+",
    re.IGNORECASE,
)


def unaccounted(db_dir: Path) -> list[str]:
    """Context sets in a spelling neither counted form matches."""
    out: list[str] = []
    for path in sorted(db_dir.glob("*.test.ts")):
        code = "\n".join(COMMENT.sub("", line) for line in path.read_text().split("\n"))
        covered = [m.span() for m in LITERAL.finditer(code)]
        for m in BROAD.finditer(code):
            if any(a <= m.start() < b for a, b in covered):
                continue
            line = code[: m.start()].count("\n") + 1
            out.append(f"{path.name}:{line}: {m.group(0).strip()}")
    return out


def census(db_dir: Path) -> dict:
    helper: list[tuple[str, str, int]] = []
    literal: list[tuple[str, int]] = []
    for path in sorted(db_dir.glob("*.test.ts")):
        # Comments are stripped line by line, so a line number in the stripped
        # text is the line number in the file.
        code = "\n".join(COMMENT.sub("", line) for line in path.read_text().split("\n"))
        for m in HELPER.finditer(code):
            helper.append((path.name, m.group(1), code[: m.start()].count("\n") + 1))
        for m in LITERAL.finditer(code):
            literal.append((path.name, code[: m.start()].count("\n") + 1))
    session = [h for h in helper if h[1] == "session"]
    transaction = [h for h in helper if h[1] == "transaction"]
    return {
        "files": sorted({h[0] for h in helper} | {l[0] for l in literal}),
        "session_helper": session,
        "transaction": transaction,
        "literal": literal,
        "total": len(helper) + len(literal),
        "session_total": len(session) + len(literal),
    }


def render(c: dict) -> list[str]:
    tx = ", ".join(f"`{f}:{line}`" for f, _scope, line in c["transaction"]) or "none"
    lit = ", ".join(f"`{f}:{line}`" for f, line in c["literal"]) or "none"
    return [
        BEGIN,
        "",
        "| context-setting call sites in `test/db/*.test.ts` | count |",
        "|---|---|",
        f"| **total population of the law** | **{c['total']}** |",
        f"| set per SESSION — `setRequestContext(… 'session')` | {len(c['session_helper'])} |",
        f"| set per SESSION — literal `set_config('app.…', …, false)` | {len(c['literal'])} |",
        f"| **set per SESSION, together — the number the pure law pins** | **{c['session_total']}** |",
        f"| set per TRANSACTION — `setRequestContext(… 'transaction')` | {len(c['transaction'])} |",
        "",
        f"Per-transaction sites: {tx}. Literal sites: {lit}.",
        "",
        "_Generated by `tools/context-sites.py` from the corpus itself; `--check` exits 1 on drift,"
        " on a listed document with no block, and on a malformed sentinel pair. **Every figure in"
        " this table** — the total, both session rows, their sum and the transaction row — is"
        " independently PINNED as an exact equality by"
        " `test/db-refusals-name-their-defence.test.ts`, **against the two spellings this census"
        " defines**: `setRequestContext(… 'session' | 'transaction')` and a literal"
        " `set_config('app.…', …, false)`. A site written in either spelling cannot be added or"
        " removed without redding the pure suite. A site written in ANY OTHER spelling is counted"
        " by neither, so a fail-closed detector reds the suite and this check when it finds a"
        " `set_config('app.…`, a bound or interpolated `set_config(` key, or a"
        " `SET`/`SET LOCAL`/`SET SESSION app.…` that neither counted form accounts for — a"
        " broad net, not a parser, and not a claim of exhaustiveness. Round 25 added the quoted GUC name `SET LOCAL \"app.…\"` (the challenger's F-44), legal PostgreSQL and a quoting variant of a shape this sentence names. **What the net does NOT see**, measured and named rather than implied: anything in `test/db/helpers/*.ts` or any non-`.test.ts` file under `test/db`, which is outside the corpus this census declares — `cluster.ts`'s own internal line lives there, and a helper's implementation is not a call site; and a key passed as a bare identifier, `set_config(key, …, false)`, which is neither a literal, a bound parameter nor an interpolation, so it falls outside every shape this sentence names and is left to that limit rather than matched, because matching it would red on ordinary settings that have nothing to do with the request context. Round 24 widened the net to `SET LOCAL`/`SET SESSION` (the challenger's B-6: the sentence named `SET app.…` while the pattern demanded `app.` immediately after `SET`, so the PostgreSQL spelling for the transaction-scoped setting this census exists to distinguish was not caught) and to a bound key, an interpolated key and `set_config (` with a space (its F-43). Two rounds of history, because the"
        " claim has been wrong twice: round 21 added two transaction sites while the law pinned only"
        " the session sum and this footnote claimed the table (B-3), and round 22's replacement"
        " sentence said \"anywhere in the corpus\" while a third spelling — the one `cluster.ts`"
        " uses, with the scope argument bound — moved neither the law nor the census (B-4)._",
        "",
        END,
    ]


def bounds(lines: list[str], name: str) -> tuple[int, int] | None:
    begins = [i for i, l in enumerate(lines) if l.strip() == BEGIN]
    ends = [i for i, l in enumerate(lines) if l.strip() == END]
    if not begins and not ends:
        return None
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        sys.exit(f"{name}: malformed sentinel pair ({len(begins)} begin, {len(ends)} end)")
    return begins[0], ends[0] + 1


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True, help="the directory holding the pack")
    ap.add_argument("--tests", required=True, help="the test/db directory of @daftar/billing")
    ap.add_argument("--check", action="store_true", help="verify instead of rewriting")
    args = ap.parse_args()

    tests = Path(args.tests)
    if not tests.is_dir():
        sys.exit(f"no test directory at {tests}")
    c = census(tests)
    if not c["files"]:
        # A census over an empty corpus is not a census. Absence of subjects is
        # a failure, never a quiet zero.
        sys.exit(f"no context-setting call sites found under {tests} — the census has no subjects")
    block = render(c)

    base = Path(args.dir)
    problems: list[str] = [
        f"UNACCOUNTED context set, in a spelling neither counted form matches: {site}"
        for site in unaccounted(tests)
    ]
    for name in DOCUMENTS:
        path = base / name
        if not path.is_file():
            problems.append(f"MISSING document: {name}")
            continue
        lines = path.read_text().split("\n")
        at = bounds(lines, name)
        if at is None:
            problems.append(f"NO CONTEXT-SITES BLOCK in a document that must carry one: {name}")
            continue
        start, end = at
        if args.check:
            if lines[start:end] != block:
                problems.append(f"CONTEXT-SITES BLOCK DRIFTED from the corpus: {name}")
        else:
            path.write_text("\n".join(lines[:start] + block + lines[end:]))

    for p in problems:
        print(p)
    verb = "checked" if args.check else "wrote"
    print(
        f"{verb} {len(DOCUMENTS)} documents, {len(problems)} problems; census: "
        f"{c['total']} sites = {len(c['session_helper'])} session + {len(c['literal'])} literal "
        f"+ {len(c['transaction'])} transaction, over {len(c['files'])} files"
    )
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
