#!/usr/bin/env python3
"""Generate or CHECK the handoff manifest's digest table.

ROUND 14, the coordinator's diff-review R-5. The table was regenerated by
hand every round, which held twice by measurement and is not a mechanism:
nothing failed when a file was ABSENT from the table, and the review's own
report was going to be absent from it. A check that only catches drift in
the rows that exist cannot catch the row that is missing — the cross-phase
lesson, now with a tool.

    python3 tools/manifest-digests.py --dir <dir>            # rewrite the table
    python3 tools/manifest-digests.py --dir <dir> --check     # exit 1 on any
                                                              # drift, absence
                                                              # or extra row

`--check` is the gate. It fails on three things, not one:
  * a row whose digest no longer matches its file (drift);
  * a `.md` **or `.json`** file in the directory with no row at all
    (absence) — round 17 added `.json` to the hashed set and this docstring
    kept saying `.md` only, which is the coordinator's S-5;
  * a row naming a file that is not there any more (an orphan).

The manifest's own row is `this file` by necessity — a file cannot carry its
own digest — and that one exception is the only one.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

MANIFEST = "P5-HANDOFF-MANIFEST.md"
HEADER = "| file | SHA256 |"
SELF_ROW = f"| `{MANIFEST}` | this file |"
REVIEWER_NOTE = "reviewer-owned, not hashed by the author"
# Group 2 is the VALUE exactly as written, so the check can tell the three
# legitimate forms apart instead of reading them all as "no digest".
ROW = re.compile(
    r"^\| `([^`]+)` \| (`[0-9a-f]{64}`|this file|" + re.escape(REVIEWER_NOTE) + r") \|$"
)

# ROUND 22, the coordinator's item 5, which is the P13 ruling applied here.
# These files are written by the REVIEWERS — the independent challenger and the
# coordinator — and the author must not present a digest of them as his own
# record: every time a reviewer appends a withdrawal or files a new report, an
# author-hashed row DRIFTS, and the author's only way to make his own gate
# green is to re-hash somebody else's document. So their rows carry a marker
# instead of a digest.
#
# It is ONE ENUMERATED LIST OF EXACT NAMES, deliberately not a name pattern: a
# pattern would silently exempt the next file that happens to match it, which
# is exactly the fail-open shape this phase keeps finding. The list is shared
# by the walk that writes the rows and by the coverage self-test below, so a
# name can never be exempt in one and hashed in the other.
REVIEWER_REPORTS: tuple[str, ...] = (
    "P5-CHALLENGE-04e72cd.md",
    "P5-CHALLENGE-07d308a.md",
    "P5-CHALLENGE-0c16546.md",
    "P5-CHALLENGE-421e425.md",
    "P5-CHALLENGE-47a56c8.md",
    "P5-CHALLENGE-4c451e6.md",
    "P5-CHALLENGE-594178c.md",
    "P5-CHALLENGE-92aa7c2.md",
    "P5-CHALLENGE-6f2c9b7.md",
    "P5-CHALLENGE-5af0c96.md",
    "P5-CHALLENGE-6171923.md",
    "P5-CHALLENGE-678564e.md",
    "P5-CHALLENGE-7a9737c.md",
    "P5-COORD-DIFF-REVIEW-2108d26.md",
    "P5-COORD-DIFF-REVIEW-4c451e6.md",
    "P5-COORD-DIFF-REVIEW-4fb8e1d.md",
)

# The DETECTOR exists to fail closed, never to exempt. A file whose name says
# it is a reviewer report but which is absent from the list above is a
# PROBLEM, so adding a report without enumerating it cannot pass unnoticed;
# and a name that matches nothing here is hashed as the author's, whatever it
# is called.
#
# ROUND 23, THE CHALLENGER'S F-42. The first version demanded exactly seven
# hex characters, so a report copied as `P5-CHALLENGE-0c165460.md` — eight —
# was hashed as the author's and `--check` returned rc 0. The consequence was
# mild (drift, never a false record) but the shape was the wrong one: a
# fail-closed net with an exact-width hole in it. Six to forty hex characters
# now, either case, with an optional `-suffix`, which covers an abbreviated
# sha, a full one, and `…-v2`. It still catches only the two name shapes the
# reviewers use; anything outside them is hashed as the author's, which is the
# safe direction.
LOOKS_LIKE_REVIEWER = re.compile(
    r"^P5-(CHALLENGE|COORD-DIFF-REVIEW)-[0-9a-fA-F]{6,40}(-[A-Za-z0-9]+)?\.md$"
)


def reviewer_list_problems(on_disk: list[str]) -> list[str]:
    """The coverage self-test of the enumerated list, used in BOTH modes."""
    problems: list[str] = []
    present = set(on_disk)
    for name in REVIEWER_REPORTS:
        if name not in present:
            problems.append(
                f"STALE reviewer-report list: {name} is enumerated but not in the pack"
            )
    for name in on_disk:
        if LOOKS_LIKE_REVIEWER.match(name) and name not in REVIEWER_REPORTS:
            problems.append(
                f"UNENUMERATED reviewer report: {name} — add it to REVIEWER_REPORTS by its exact "
                "name; it is not exempt by looking like one"
            )
    return problems


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def table_bounds(lines: list[str]) -> tuple[int, int]:
    try:
        start = lines.index(HEADER)
    except ValueError:
        sys.exit(f"{MANIFEST} has no digest table (no line {HEADER!r})")
    end = start + 1
    while end < len(lines) and (lines[end].startswith("|") or lines[end].startswith("|---")):
        end += 1
    return start, end


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True, help="the directory holding the pack")
    ap.add_argument("--check", action="store_true", help="verify instead of rewriting")
    args = ap.parse_args()

    base = Path(args.dir)
    manifest = base / MANIFEST
    if not manifest.is_file():
        sys.exit(f"no {MANIFEST} in {base}")

    # ROUND 17: `*.md` alone stopped being the pack. `P5-STATUS.json` is now
    # the SOURCE the status block in five documents is generated from, so a
    # digest table that hashed only the Markdown would have left the one file
    # that decides what those five documents SAY outside the hashed set —
    # the same shape as a check that cannot look at what it reassures about.
    on_disk = sorted(p.name for p in base.glob("*.md")) + sorted(p.name for p in base.glob("*.json"))
    lines = manifest.read_text().split("\n")
    start, end = table_bounds(lines)

    list_problems = reviewer_list_problems(on_disk)

    if not args.check:
        if list_problems:
            for p in list_problems:
                print(p)
            print("refusing to write the table while the reviewer-report list is wrong")
            return 1
        rows = [HEADER, "|---|---|"]
        for name in on_disk:
            if name == MANIFEST:
                rows.append(SELF_ROW)
            elif name in REVIEWER_REPORTS:
                rows.append(f"| `{name}` | {REVIEWER_NOTE} |")
            else:
                rows.append(f"| `{name}` | `{digest(base / name)}` |")
        manifest.write_text("\n".join(lines[:start] + rows + lines[end:]))
        print(
            f"wrote {len(rows) - 2} rows for {len(on_disk)} files in {base} "
            f"({len(REVIEWER_REPORTS)} reviewer-owned, not hashed)"
        )
        return 0

    # ROUND 17, THE COORDINATOR'S N-6. This used to be a plain dict
    # assignment, so two rows naming the same file COLLAPSED and the last one
    # won. Measured: a WRONG duplicate digest row placed BEFORE the correct
    # one gave `30 rows, 0 problems`, rc 0 — a checker that cannot see a
    # contradiction in the table it is checking. Rows are counted per name
    # now, and more than one is a problem of its own: the right answer to
    # "which of these two digests is the file's?" is to refuse, not to pick.
    listed: dict[str, str] = {}
    seen: dict[str, int] = {}
    malformed: list[str] = []
    for line in lines[start:end]:
        m = ROW.match(line)
        if m:
            seen[m.group(1)] = seen.get(m.group(1), 0) + 1
            listed[m.group(1)] = m.group(2)
        elif line.strip() not in ("", HEADER, "|---|---|"):
            # ROUND 18, found while building S-5's positive control. `ROW`
            # requires 64 hex characters, so a line INSIDE the table that
            # looks like a row but is not one — a truncated digest, a stray
            # pipe — was not a row and not a problem: it was nothing. A
            # duplicate planted that way reported clean, which is N-6's own
            # failure wearing different clothes. A line in the table is now
            # either a row or a problem.
            malformed.append(line.strip()[:60])

    problems: list[str] = list(list_problems)
    for line in malformed:
        problems.append(f"MALFORMED line inside the digest table, neither a row nor a heading: {line}")
    for name, n in sorted(seen.items()):
        if n > 1:
            problems.append(f"DUPLICATE rows ({n}) for: {name}")
    for name in on_disk:
        if name not in listed:
            problems.append(f"ABSENT from the table: {name}")
            continue
        value = listed[name]
        if name == MANIFEST:
            # A file cannot carry its own digest; the row must say so and
            # must not be a digest pretending to be one.
            if value != "this file":
                problems.append("the manifest's own row must read 'this file', not a digest")
        elif name in REVIEWER_REPORTS:
            # The author must neither hash a reviewer's report nor leave the
            # row off: the marker is the only accepted value.
            if value != REVIEWER_NOTE:
                problems.append(
                    f"REVIEWER-OWNED file must carry '{REVIEWER_NOTE}', not a digest: {name}"
                )
        elif value == REVIEWER_NOTE:
            problems.append(
                f"MARKED reviewer-owned but not enumerated as one, so it must be hashed: {name}"
            )
        elif value != f"`{digest(base / name)}`":
            problems.append(f"DRIFTED: {name}")
    for name in listed:
        if name not in on_disk:
            problems.append(f"ORPHAN row, no such file: {name}")

    for p in problems:
        print(p)
    # S-5's second half: `len(listed)` counts NAMES, so the summary said
    # "34 rows" while 35 row lines existed and one name was duplicated. The
    # duplicate was still reported as a problem above — the summary was
    # merely unable to say so. Both numbers are printed now.
    row_lines = sum(seen.values())
    rows_text = f"{row_lines} rows" if row_lines == len(listed) else f"{row_lines} row lines for {len(listed)} names"
    print(f"{len(on_disk)} files, {rows_text}, {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
