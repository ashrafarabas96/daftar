#!/usr/bin/env -S python3 -I
"""Generate or CHECK the handoff manifest's digest table.

ROUND 14, the coordinator's diff-review R-5. The table was regenerated by
hand every round, which held twice by measurement and is not a mechanism:
nothing failed when a file was ABSENT from the table, and the review's own
report was going to be absent from it. A check that only catches drift in
the rows that exist cannot catch the row that is missing — the cross-phase
lesson, now with a tool.

    python3 -I tools/manifest-digests.py --dir <dir>            # rewrite the table
    python3 -I tools/manifest-digests.py --dir <dir> --check     # exit 1 on any
                                                                 # drift, absence
                                                                 # or extra row

`--check` is the gate. It fails on three things, not one:
  * a row whose digest no longer matches its file (drift);
  * ANY file in the directory with no row at all (absence). Round 17 hashed
    `.md` and `.json`; round 27 hashes every file, because a list of
    extensions exempts by looking rather than by being named, and a
    `P5-EXPORT.txt` measurably slipped through both the table and the seal's
    freshness ordering (the challenger's F-48);
  * a row naming a file that is not there any more (an orphan).

The manifest's own row is `this file` by necessity — a file cannot carry its
own digest — and that one exception is the only one.
"""
from __future__ import annotations

# B-9, round 27. This tool must run ISOLATED: `python3 -I tools/manifest-digests.py`.
# Without `-I`, the interpreter puts `PYTHONPATH` and the user site directory on
# `sys.path` BEFORE any line here runs, so a shadowed stdlib module — or a
# `sitecustomize.py`, which `site` imports at startup — decides what this tool
# computes, in a tool whose whole purpose is to be the thing a reader does not
# have to trust.
#
# It REFUSES rather than re-execing itself with `-I`. Round 27's first attempt
# re-exec'd, which re-reads this file from disk: code that has already lost the
# startup race can rewrite the exec target, and the isolated process then runs
# the attacker's file while LOOKING clean.
# `sys` is a builtin module, so the guard cannot be defeated by shadowing a
# stdlib import, and it stands above every other import in this file.
#
# ROUND 28, THE COORDINATOR'S F-50, RATED P1. What the wording here used to claim
# was FALSE, and the correction is the finding. Run this tool WITHOUT `-I` and
# `site` imports `sitecustomize` — and `usercustomize` — at interpreter startup,
# BEFORE line 1 of this file: code is loaded before the check, and the refusal CAN
# be redirected. Measured: a plant on `PYTHONPATH`, reached through the un-isolated
# command this file's own docstring used to print, produced a forged `0 problems`
# at rc 0 over a pack with a drifted file.
#
# AND THE GUARD ITSELF IS FORGEABLE, which is the challenger's §9 and the reason
# nothing here may be read as establishing isolation. `sys.flags` is an ordinary
# writable attribute of an ordinary module, so a startup plant can hand this check
# a `flags` whose `isolated` is 1: measured, an un-isolated run then printed NO
# refusal and exited 0. THE ABSENCE OF THE REFUSAL IS THEREFORE NOT EVIDENCE OF
# ISOLATION, and an un-isolated run that looks clean proves nothing about what
# computed its figures.
#
# So this guard buys one thing only: an un-isolated run with nothing already
# planted against it says so instead of computing. Inside a non-isolated run it
# defends nothing and attests nothing. The real control is `-I` AT THE CALL SITE —
# which is why every usage line here, every command in the pack and every child
# this tool spawns carries it, and why a test asserts that and reds if one loses
# it.
#
# ROUND 28, F-50's companion, stated rather than coded: this tests the `-I` FLAG,
# not the condition, so `python3 -E -s` is refused although it also clears
# `PYTHONPATH` and the user site directory. That is deliberate. `-E -s` still
# leaves the script's own directory first on `sys.path`, which is the one place
# an attacker who can write next to this file does not need `PYTHONPATH` at all.
# One flag, one documented command, nothing to reason about at the call site.
import sys

if not sys.flags.isolated:
    raise SystemExit(
        "refusing to run without -I: run `python3 -I tools/manifest-digests.py`. "
        "Without isolation PYTHONPATH and the user site directory are on sys.path "
        "before this file is read, so what this tool computes is not this tool's."
    )


import argparse
import hashlib
import io
import json
import re
from pathlib import Path

MANIFEST = "P5-HANDOFF-MANIFEST.md"
HEADER = "| file | SHA256 |"
SELF_ROW = f"| `{MANIFEST}` | this file |"
REVIEWER_NOTE = "reviewer-owned, not hashed by the author"
# Group 2 is the VALUE exactly as written, so the check can tell the three
# legitimate forms apart instead of reading them all as "no digest".
ROW = re.compile(
    r"^\| `([^`]+)` \| (`[0-9a-f]{64}`|this file|" + re.escape(REVIEWER_NOTE) + r") \|$"
)

# ROUND 22, the coordinator's item 5, which is the P13 ruling applied here.
# These files are written by the REVIEWERS — the independent challenger and the
# coordinator — and the author must not present a digest of them as his own
# record: every time a reviewer appends a withdrawal or files a new report, an
# author-hashed row DRIFTS, and the author's only way to make his own gate
# green is to re-hash somebody else's document. So their rows carry a marker
# instead of a digest.
#
# It is ONE ENUMERATED LIST OF EXACT NAMES, deliberately not a name pattern: a
# pattern would silently exempt the next file that happens to match it, which
# is exactly the fail-open shape this phase keeps finding. The list is shared
# by the walk that writes the rows and by the coverage self-test below, so a
# name can never be exempt in one and hashed in the other.
REVIEWER_REPORTS_FILE = "reviewer-reports.json"


def reviewer_reports() -> tuple[str, ...]:
    """The enumerated names, read from the ONE file both instruments read.

    ROUND 28, THE CHALLENGER'S B-10 (P1). The names used to live in this file
    as a tuple, while `test/tool-commands-are-isolated.test.ts` described the
    same set with a name PATTERN thirty lines below a commit message arguing
    that exemptions must never be keyed on shape. Measured, identical bytes one
    name apart: an author document called `P5-CHALLENGE-1234567.md` was exempt
    from that law, and three reviewer names this tool accepts — eight hex, a
    `-R2` suffix, uppercase — were scanned and blamed on the author. A set
    described twice is two sets.

    It FAILS CLOSED. A missing, unreadable, malformed or empty list refuses;
    nothing here falls back to a pattern, because a fallback is the hole.
    """
    path = Path(__file__).resolve().parent / REVIEWER_REPORTS_FILE
    try:
        raw = json.loads(io.open(path, encoding="utf-8").read())
    except FileNotFoundError:
        raise SystemExit(f"no {REVIEWER_REPORTS_FILE} beside this tool at {path}")
    except json.JSONDecodeError as exc:
        raise SystemExit(f"{REVIEWER_REPORTS_FILE} is not valid JSON: {exc}")
    if not isinstance(raw, dict):
        raise SystemExit(f"{REVIEWER_REPORTS_FILE} must be a JSON object")
    names = raw.get("reviewer_reports")
    if not isinstance(names, list) or not names:
        raise SystemExit(
            f"{REVIEWER_REPORTS_FILE} has no non-empty 'reviewer_reports' list — refusing rather "
            f"than treating every reviewer report as the author's"
        )
    if not all(isinstance(n, str) and n and "/" not in n for n in names):
        raise SystemExit(f"{REVIEWER_REPORTS_FILE}: every entry must be a bare file name")
    if len(set(names)) != len(names):
        raise SystemExit(f"{REVIEWER_REPORTS_FILE} lists a name twice")
    return tuple(names)


REVIEWER_REPORTS: tuple[str, ...] = reviewer_reports()

# The DETECTOR exists to fail closed, never to exempt. A file whose name says
# it is a reviewer report but which is absent from the list above is a
# PROBLEM, so adding a report without enumerating it cannot pass unnoticed;
# and a name that matches nothing here is hashed as the author's, whatever it
# is called.
#
# ROUND 23, THE CHALLENGER'S F-42. The first version demanded exactly seven
# hex characters, so a report copied as `P5-CHALLENGE-0c165460.md` — eight —
# was hashed as the author's and `--check` returned rc 0. The consequence was
# mild (drift, never a false record) but the shape was the wrong one: a
# fail-closed net with an exact-width hole in it. Six to forty hex characters
# now, either case, with an optional `-suffix`, which covers an abbreviated
# sha, a full one, and `…-v2`. It still catches only the two name shapes the
# reviewers use; anything outside them is hashed as the author's, which is the
# safe direction.
def looks_like_reviewer_pattern() -> str:
    """The name SHAPE, read from the same file as the enumerated list.

    ROUND 30, the challenger's F-53. The shape decides WORDING and detection,
    never an exemption — that distinction is B-10 — and the other instrument
    needs the same shape to say the same true sentence about the same file, so
    it is not described twice either. Fails closed with the list.
    """
    path = Path(__file__).resolve().parent / REVIEWER_REPORTS_FILE
    raw = json.loads(io.open(path, encoding="utf-8").read())
    pattern = raw.get("looks_like_reviewer")
    if not isinstance(pattern, str) or not pattern:
        raise SystemExit(
            f"{REVIEWER_REPORTS_FILE} has no 'looks_like_reviewer' pattern — refusing rather than "
            f"detecting reviewer-looking names by a shape written somewhere else"
        )
    try:
        return re.compile(pattern).pattern
    except re.error as exc:
        raise SystemExit(f"{REVIEWER_REPORTS_FILE}: 'looks_like_reviewer' is not a regex: {exc}")


LOOKS_LIKE_REVIEWER = re.compile(looks_like_reviewer_pattern())


def reviewer_list_problems(on_disk: list[str]) -> list[str]:
    """The coverage self-test of the enumerated list, used in BOTH modes."""
    problems: list[str] = []
    present = set(on_disk)
    for name in REVIEWER_REPORTS:
        if name not in present:
            problems.append(
                f"STALE reviewer-report list: {name} is enumerated but not in the pack"
            )
    for name in on_disk:
        # F-54, ROUND 32. `match` plus a `$` anchor is NOT the JS predicate:
        # Python's `$` also matches just before a final newline, so
        # `P5-CHALLENGE-9bd33bd.md\n` -- a legal POSIX file name -- was True
        # here and false in the other instrument, which routed one name two
        # ways. `fullmatch` has to consume the whole name, so the two engines
        # agree. Measured both ways before and after; the restriction is
        # written beside the pattern in reviewer-reports.json.
        if LOOKS_LIKE_REVIEWER.fullmatch(name) and name not in REVIEWER_REPORTS:
            problems.append(
                f"UNENUMERATED reviewer report: {name} — add it to REVIEWER_REPORTS by its exact "
                "name; it is not exempt by looking like one"
            )
    return problems


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def table_bounds(lines: list[str]) -> tuple[int, int]:
    try:
        start = lines.index(HEADER)
    except ValueError:
        sys.exit(f"{MANIFEST} has no digest table (no line {HEADER!r})")
    end = start + 1
    while end < len(lines) and (lines[end].startswith("|") or lines[end].startswith("|---")):
        end += 1
    return start, end


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True, help="the directory holding the pack")
    ap.add_argument("--check", action="store_true", help="verify instead of rewriting")
    args = ap.parse_args()

    base = Path(args.dir)
    manifest = base / MANIFEST
    if not manifest.is_file():
        sys.exit(f"no {MANIFEST} in {base}")

    # ROUND 17: `*.md` alone stopped being the pack. `P5-STATUS.json` is now
    # the SOURCE the status block in five documents is generated from, so a
    # digest table that hashed only the Markdown would have left the one file
    # that decides what those five documents SAY outside the hashed set —
    # the same shape as a check that cannot look at what it reassures about.
    # ROUND 27, THE CHALLENGER'S F-48. Round 17 widened the hashed set from
    # `*.md` to `*.md` + `*.json` and the set stayed a LIST OF EXTENSIONS, which
    # is the same shape as a name pattern deciding who authored a file: it
    # exempts by looking, not by being named. Measured on a byte copy: with a
    # `P5-EXPORT.txt` in the pack, `--check` printed `42 files, 42 rows, 0
    # problems` at rc 0 while the directory held 43 files, and the seal named a
    # document fifteen minutes OLDER as the newest, because the freshness
    # ordering globbed the same two extensions. The same bytes renamed `.md`
    # were caught at rc 1 — one finding, with its own control.
    #
    # The hashed set is now EVERY FILE in the directory. The reviewer-owned
    # tuple is the only exemption, as it has been since round 22, and the
    # manifest's own row is `this file` by necessity. Directories are skipped
    # because a directory has no bytes to hash; nothing else is.
    on_disk = sorted(p.name for p in base.iterdir() if p.is_file())
    lines = manifest.read_text().split("\n")
    start, end = table_bounds(lines)

    list_problems = reviewer_list_problems(on_disk)

    if not args.check:
        if list_problems:
            for p in list_problems:
                print(p)
            print("refusing to write the table while the reviewer-report list is wrong")
            return 1
        rows = [HEADER, "|---|---|"]
        for name in on_disk:
            if name == MANIFEST:
                rows.append(SELF_ROW)
            elif name in REVIEWER_REPORTS:
                rows.append(f"| `{name}` | {REVIEWER_NOTE} |")
            else:
                rows.append(f"| `{name}` | `{digest(base / name)}` |")
        manifest.write_text("\n".join(lines[:start] + rows + lines[end:]))
        print(
            f"wrote {len(rows) - 2} rows for {len(on_disk)} files in {base} "
            f"({len(REVIEWER_REPORTS)} reviewer-owned, not hashed)"
        )
        return 0

    # ROUND 17, THE COORDINATOR'S N-6. This used to be a plain dict
    # assignment, so two rows naming the same file COLLAPSED and the last one
    # won. Measured: a WRONG duplicate digest row placed BEFORE the correct
    # one gave `30 rows, 0 problems`, rc 0 — a checker that cannot see a
    # contradiction in the table it is checking. Rows are counted per name
    # now, and more than one is a problem of its own: the right answer to
    # "which of these two digests is the file's?" is to refuse, not to pick.
    listed: dict[str, str] = {}
    seen: dict[str, int] = {}
    malformed: list[str] = []
    for line in lines[start:end]:
        m = ROW.match(line)
        if m:
            seen[m.group(1)] = seen.get(m.group(1), 0) + 1
            listed[m.group(1)] = m.group(2)
        elif line.strip() not in ("", HEADER, "|---|---|"):
            # ROUND 18, found while building S-5's positive control. `ROW`
            # requires 64 hex characters, so a line INSIDE the table that
            # looks like a row but is not one — a truncated digest, a stray
            # pipe — was not a row and not a problem: it was nothing. A
            # duplicate planted that way reported clean, which is N-6's own
            # failure wearing different clothes. A line in the table is now
            # either a row or a problem.
            malformed.append(line.strip()[:60])

    problems: list[str] = list(list_problems)
    for line in malformed:
        problems.append(f"MALFORMED line inside the digest table, neither a row nor a heading: {line}")
    for name, n in sorted(seen.items()):
        if n > 1:
            problems.append(f"DUPLICATE rows ({n}) for: {name}")
    for name in on_disk:
        if name not in listed:
            problems.append(f"ABSENT from the table: {name}")
            continue
        value = listed[name]
        if name == MANIFEST:
            # A file cannot carry its own digest; the row must say so and
            # must not be a digest pretending to be one.
            if value != "this file":
                problems.append("the manifest's own row must read 'this file', not a digest")
        elif name in REVIEWER_REPORTS:
            # The author must neither hash a reviewer's report nor leave the
            # row off: the marker is the only accepted value.
            if value != REVIEWER_NOTE:
                problems.append(
                    f"REVIEWER-OWNED file must carry '{REVIEWER_NOTE}', not a digest: {name}"
                )
        elif value == REVIEWER_NOTE:
            problems.append(
                f"MARKED reviewer-owned but not enumerated as one, so it must be hashed: {name}"
            )
        elif value != f"`{digest(base / name)}`":
            problems.append(f"DRIFTED: {name}")
    for name in listed:
        if name not in on_disk:
            problems.append(f"ORPHAN row, no such file: {name}")

    for p in problems:
        print(p)
    # S-5's second half: `len(listed)` counts NAMES, so the summary said
    # "34 rows" while 35 row lines existed and one name was duplicated. The
    # duplicate was still reported as a problem above — the summary was
    # merely unable to say so. Both numbers are printed now.
    row_lines = sum(seen.values())
    rows_text = f"{row_lines} rows" if row_lines == len(listed) else f"{row_lines} row lines for {len(listed)} names"
    print(f"{len(on_disk)} files, {rows_text}, {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
